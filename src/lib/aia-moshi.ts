export async function getAiaMoshi1Questions(): Promise<AiaQuestionData[]> {
  const all = await getAllAiaQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = AIA_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== AIA_MOSHI_1_SLUGS.length) {
    const missing = AIA_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`aia-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
