export async function getCacMoshi1Questions(): Promise<CacQuestionData[]> {
  const all = await getAllCacQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = CAC_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== CAC_MOSHI_1_SLUGS.length) {
    const missing = CAC_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`cac-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
