export async function getCccMoshi1Questions(): Promise<CccQuestionData[]> {
  const all = await getAllCccQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = CCC_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== CCC_MOSHI_1_SLUGS.length) {
    const missing = CCC_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`ccc-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
