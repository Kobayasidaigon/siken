export async function getCcmMoshi1Questions(): Promise<CcmQuestionData[]> {
  const all = await getAllCcmQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = CCM_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== CCM_MOSHI_1_SLUGS.length) {
    const missing = CCM_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`ccm-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
