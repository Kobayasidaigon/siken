export async function getChintaiMoshi1Questions(): Promise<ChintaiQuestionData[]> {
  const all = await getAllChintaiQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = CHINTAI_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== CHINTAI_MOSHI_1_SLUGS.length) {
    const missing = CHINTAI_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`chintai-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
