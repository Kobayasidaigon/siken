export const DXA_MOSHI_PASS_POINTS = 462;

export async function getDxaMoshi1Questions(): Promise<DxaQuestionData[]> {
  const all = await getAllDxaQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = DXA_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== DXA_MOSHI_1_SLUGS.length) {
    const missing = DXA_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`dxa-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
