export async function getDxoMoshi1Questions(): Promise<DxoQuestionData[]> {
  const all = await getAllDxoQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = DXO_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== DXO_MOSHI_1_SLUGS.length) {
    const missing = DXO_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`dxo-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
