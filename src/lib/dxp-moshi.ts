export async function getDxpMoshi1Questions(): Promise<DxpQuestionData[]> {
  const all = await getAllDxpQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = DXP_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== DXP_MOSHI_1_SLUGS.length) {
    const missing = DXP_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`dxp-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
