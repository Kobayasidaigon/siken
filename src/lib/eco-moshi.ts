/**
 * 固定ペーパーの50問を ECO_MOSHI_1_SLUGS の順序どおりに返す。
 * 問題ファイルが見つからないものは黙って落とすのではなくビルドを落とす
 * (問題番号の付け替えなどで模試が静かに短くなる事故を防ぐため)。
 */
export async function getEcoMoshi1(): Promise<EcoMoshiQuestion[]> {
  const all = await getAllEcoQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  return ECO_MOSHI_1_SLUGS.map((slug) => {
    const q = bySlug.get(slug);
    if (!q) {
      throw new Error(`[eco-moshi] 模試の問題が見つかりません: ${slug}`);
    }
    return { ...q, points: ECO_MOSHI_POINTS_PER_QUESTION };
  });
}
