export async function getGaiaMoshi1Questions(): Promise<GaiaQuestionData[]> {
  const all = await getAllGaiaQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = GAIA_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== GAIA_MOSHI_1_SLUGS.length) {
    const missing = GAIA_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`gaia-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
