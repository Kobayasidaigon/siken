export async function getHadMoshi1Questions(): Promise<HadQuestionData[]> {
  const all = await getAllHadQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = HAD_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== HAD_MOSHI_1_SLUGS.length) {
    const missing = HAD_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`had-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
