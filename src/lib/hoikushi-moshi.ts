export async function getHoikushiMoshi1Questions(): Promise<HoikushiQuestionData[]> {
  const all = await getAllHoikushiQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = HOIKUSHI_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== HOIKUSHI_MOSHI_1_SLUGS.length) {
    const missing = HOIKUSHI_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`hoikushi-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
