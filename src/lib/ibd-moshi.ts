export async function getIbdMoshi1Questions(): Promise<IbdQuestionData[]> {
  const all = await getAllIbdQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = IBD_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== IBD_MOSHI_1_SLUGS.length) {
    const missing = IBD_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`ibd-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
