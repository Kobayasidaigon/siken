export async function getIsecMoshi1Questions(): Promise<IsecQuestionData[]> {
  const all = await getAllIsecQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = ISEC_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== ISEC_MOSHI_1_SLUGS.length) {
    const missing = ISEC_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`isec-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
