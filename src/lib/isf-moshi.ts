export async function getIsfMoshi1Questions(): Promise<IsfQuestionData[]> {
  const all = await getAllIsfQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = ISF_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== ISF_MOSHI_1_SLUGS.length) {
    const missing = ISF_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`isf-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
