export async function getItpassMoshi1Questions(): Promise<ItpassQuestionData[]> {
  const all = await getAllItpassQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = ITPASS_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== ITPASS_MOSHI_1_SLUGS.length) {
    const missing = ITPASS_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`itpass-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
