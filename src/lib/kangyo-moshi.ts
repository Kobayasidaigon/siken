export async function getKangyoMoshi1Questions(): Promise<KangyoQuestionData[]> {
  const all = await getAllKangyoQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = KANGYO_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== KANGYO_MOSHI_1_SLUGS.length) {
    const missing = KANGYO_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`kangyo-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
