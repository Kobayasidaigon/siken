export async function getKashikinMoshi1Questions(): Promise<QuestionData[]> {
  const all = await getAllQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = KASHIKIN_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== KASHIKIN_MOSHI_1_SLUGS.length) {
    const missing = KASHIKIN_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`kashikin-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
