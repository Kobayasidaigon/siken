export async function getKyoinMoshi1Questions(): Promise<KyoinQuestionData[]> {
  const all = await getAllKyoinQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = KYOIN_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== KYOIN_MOSHI_1_SLUGS.length) {
    const missing = KYOIN_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`kyoin-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
