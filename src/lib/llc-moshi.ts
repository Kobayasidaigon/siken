export async function getLlcMoshi1Questions(): Promise<LlcQuestionData[]> {
  const all = await getAllLlcQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = LLC_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== LLC_MOSHI_1_SLUGS.length) {
    const missing = LLC_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`llc-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
