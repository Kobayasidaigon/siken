export async function getPiiMoshi1Questions(): Promise<PiiQuestionData[]> {
  const all = await getAllPiiQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = PII_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== PII_MOSHI_1_SLUGS.length) {
    const missing = PII_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`pii-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
