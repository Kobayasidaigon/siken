/** 課題Ⅱ(51〜100問目)の練習問題を出題順に返す */
export async function getPiiMoshi1Kadai2Questions(): Promise<PiiQuestionData[]> {
  const all = await getAllPiiQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = PII_MOSHI_1_KADAI2_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== PII_MOSHI_1_KADAI2_SLUGS.length) {
    const missing = PII_MOSHI_1_KADAI2_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`pii-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
