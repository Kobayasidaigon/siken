/**
 * 特定商取引法に基づく表記に載せる販売事業者の情報。2026-09-09 追加。
 *
 * 【なぜ必要か】
 * 第2回模試(moshi2)を9資格で有料販売しているのに、特定商取引法に基づく表記のページが
 * サイトに存在しなかった。通信販売の広告表示義務(特商法11条)に直接かかる状態だったので、
 * /tokushoho/ を新設し、その値をこの1ファイルに集約した。
 *
 * 【氏名・住所・電話番号は省略できない】
 * about ページの運営者情報はペンネーム「熊太郎」だけで、法律が求める水準を満たさない。
 * 通信販売では、販売業者の氏名(法人なら名称)・住所・電話番号の表示が求められ、
 * ペンネームやフォームでの代替は認められていない。個人事業でも同じ扱いになる。
 *
 * 【未設定のときの挙動】
 * 下の3項目が空のあいだ、/tokushoho/ は「準備中」の断りを出し、robots は noindex にする。
 * 事実と違う表記を公開するより、未完成であることを明示するほうが害が小さい。
 * 値を入れれば自動で通常表示に切り替わり、noindex も外れる。
 *
 * 【販売を止めていないことについて】
 * 表記が未完成でも決済は従来どおり動く。売上を勝手に止める判断は運営者のものなので、
 * ここではしない。ただし表記が埋まるまでは違反状態が続くため、最優先で埋めること。
 */

export const SELLER = {
  /** 販売業者の氏名。個人事業なら戸籍上の氏名、法人なら登記上の名称。ペンネーム不可 */
  name: "",
  /** 所在地。市区町村・番地まで。私書箱やバーチャルオフィスの可否は要確認 */
  address: "",
  /** 電話番号。つながる番号であること。受付時間を添えてよい */
  phone: "",
  /** 電話の受付時間(任意)。空なら表示しない */
  phoneHours: "",
  /** 運営責任者名(任意)。name と同じなら空でよい */
  manager: "",
  /** 問い合わせ用のメールアドレス(任意)。空ならフォームのみ案内する */
  email: "",
} as const;

/** 法律上省略できない3項目がすべて埋まっているか */
export function isSellerConfigured(): boolean {
  return Boolean(SELLER.name && SELLER.address && SELLER.phone);
}

/** 表示用。未設定なら「（未設定）」ではなく null を返し、呼び出し側で断りを出す */
export function sellerValue(key: "name" | "address" | "phone"): string | null {
  const v = SELLER[key];
  return v ? v : null;
}
