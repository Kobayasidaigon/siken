export async function getShakaiMoshi1Questions(): Promise<ShakaiQuestionData[]> {
  const all = await getAllShakaiQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = SHAKAI_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== SHAKAI_MOSHI_1_SLUGS.length) {
    const missing = SHAKAI_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`shakai-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
