export async function getTouhanMoshi1Questions(): Promise<TouhanQuestionData[]> {
  const all = await getAllTouhanQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = TOUHAN_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== TOUHAN_MOSHI_1_SLUGS.length) {
    const missing = TOUHAN_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`touhan-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
