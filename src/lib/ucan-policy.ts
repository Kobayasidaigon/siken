/** 合格率・合格者数に類する語。 */
const PASS_RATE_TERM = "(?:合格率|合格者数|合格実績)";

/** 割合・人数の数値表現 (全角数字・桁区切りを含む)。 */
const RATE_VALUE = "[0-9０-９][0-9０-９,，.．]*\\s*(?:%|％|割|ポイント|人)";

/** 本文用: 合格率系の語の直後(20字以内)に数値が続く = 数値を伴う訴求。 */
const NUMERIC_CLAIM = new RegExp(`${PASS_RATE_TERM}[^。\\n]{0,20}${RATE_VALUE}`);

/** 見出し用: 語が出てくるだけで主題とみなす。 */
const ANY_TERM = new RegExp(PASS_RATE_TERM);

/** HTML タグを落として素のテキストにする (表のセル境界で数値が切れるのを防ぐ)。 */
function stripTags(s: string): string {
  return s.replace(/<[^>]*>/g, "");
}

/**
 * ユーキャンの講座広告をこの面に出してよいか。
 * タイトル・ディスクリプションに合格率系の語がある記事、または
 * 本文に数値を伴う合格率・合格者数の表記がある記事には出さない。
 */
export function canShowUcanAd(source: {
  title?: string;
  description?: string;
  content?: string;
}): boolean {
  const heading = `${source.title ?? ""}\n${source.description ?? ""}`;
  if (ANY_TERM.test(heading)) return false;
  return !NUMERIC_CLAIM.test(stripTags(source.content ?? ""));
}
