export async function getWlcMoshi1Questions(): Promise<WlcQuestionData[]> {
  const all = await getAllWlcQuestions();
  const bySlug = new Map(all.map((q) => [q.slug, q]));
  const found = WLC_MOSHI_1_SLUGS.flatMap((s) => {
    const q = bySlug.get(s);
    return q ? [q] : [];
  });
  if (found.length !== WLC_MOSHI_1_SLUGS.length) {
    const missing = WLC_MOSHI_1_SLUGS.filter((s) => !bySlug.has(s));
    throw new Error(`wlc-moshi: 模試の問題が見つかりません: ${missing.join(", ")}`);
  }
  return found;
}
